#!/usr/bin/env python3

"""Writes the results tables into README.md, built only from the benchmark and eval data.

The tables sit between two marker lines in README.md. `make readme` rewrites them;
test_readme.py fails when they are out of date (part of `make usage-test`, `make check`
and CI), so no result in the README is typed by hand.
"""

import argparse
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import report  # noqa: E402

START = "<!-- results:start (generated by `make readme` from benchmarks/results and evals/results.csv; do not edit) -->"
END = "<!-- results:end -->"
EVAL_CONFIGS = ("baseline", "harness")


def benchmark_section(results):
    by_config = {c: [r for r in results if r["config"] == c] for c in report.CONFIGS}
    if not all(by_config.values()):
        raise report.BadData("the benchmark needs runs for both configurations")
    rows = []
    for config, items in by_config.items():
        rows.append([config, len(items), report.share(items, "ok"), report.share(items, "first_pass"),
                     f"{report.mean([i['calls'] for i in items]):.0f}",
                     f"{report.mean([sum(i['tokens'].values()) for i in items]):,.0f}",
                     f"${report.mean([i['cost'] for i in items]):.2f}"])
    base, harness = (report.mean([i["cost"] for i in by_config[c]]) for c in report.CONFIGS)
    task_rows = []
    for task in report.TASKS:
        cells = {c: [r for r in by_config[c] if r["task"] == task] for c in report.CONFIGS}
        if not all(cells.values()):
            continue
        task_rows.append([task] + [report.share(cells[c], "ok") for c in report.CONFIGS]
                         + [f"${report.mean([i['cost'] for i in cells[c]]):.2f}" for c in report.CONFIGS])
    return [
        f"**Benchmark** ({len(results)} runs: {len(report.TASKS)} tasks, 2 configurations, same model)",
        "",
        report.table(["Config", "Runs", "Success", "First-pass CI", "API calls", "Tokens", "Cost per run"], rows),
        "",
        f"Averages per run. Harness cost per run vs baseline: {(harness - base) / base * 100:+.0f}%.",
        "",
        report.table(["Task", "Success, baseline", "Success, harness", "Cost, baseline", "Cost, harness"], task_rows),
    ]


def eval_section(rows):
    if not rows:
        raise report.BadData("evals/results.csv has no runs")
    seen, total, lines = {}, {}, []
    for row in rows:
        key = (row["eval_id"], row["config"])
        total[key] = total.get(key, 0) + 1
    passed = 0
    for row in rows:
        if row["config"] not in EVAL_CONFIGS:
            raise report.BadData(f"eval {row['eval_id']}: unknown config {row['config']!r}")
        for field in ("agent_introduced_violation", "passed"):
            if row[field] not in ("yes", "no"):
                raise report.BadData(f"eval {row['eval_id']}: {field} must be yes or no, not {row[field]!r}")
        key = (row["eval_id"], row["config"])
        seen[key] = seen.get(key, 0) + 1
        name = row["eval_id"] + (f" run {seen[key]}" if total[key] > 1 else "")
        pr = f"#{row['pr']}" if row["pr"].isdigit() else "none"
        passed += row["passed"] == "yes"
        lines.append([name, row["config"], pr, row["agent_introduced_violation"], row["first_layer"],
                      row["mergeable_without_approval"], row["passed"]])
    summary = f"{passed} of {len(rows)} runs passed"
    if passed == len(rows):
        summary += ": no violation became mergeable without the owner's approval"
    return [
        f"**Safety evals** ({len(rows)} runs of 4 planted violations; details in [evals/](evals/))",
        "",
        report.table(["Eval", "Config", "PR", "Violation in the PR", "Stopped by", "Merge state", "Passed"], lines),
        "",
        summary + ".",
    ]


def block(repo=REPO):
    bench = os.path.join(repo, "benchmarks")
    price_rows = report.read_csv(os.path.join(bench, "prices.csv"))
    prices = {p["model"]: p for p in price_rows}
    results = report.runs_with_usage(report.read_csv(os.path.join(bench, "results", "runs.csv")),
                                     report.read_csv(os.path.join(bench, "results", "usage.csv")), prices)
    evals = report.read_csv(os.path.join(repo, "evals", "results.csv"))
    return "\n".join([START, ""] + benchmark_section(results) + [""] + eval_section(evals) + ["", END])


def replace_block(text, new_block):
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        raise report.BadData("README.md needs exactly one results:start line before one results:end line")
    before, rest = text.split(START, 1)
    after = rest.split(END, 1)[1]
    return before + new_block + after


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if README.md is out of date; change nothing")
    parser.add_argument("--repo", default=REPO)
    args = parser.parse_args(argv)
    path = os.path.join(args.repo, "README.md")
    try:
        with open(path, encoding="utf-8") as f:
            current = f.read()
        wanted = replace_block(current, block(args.repo))
    except (report.BadData, OSError, KeyError, ValueError, csv.Error) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if wanted != current:
            print("FAIL: the README results are out of date. Run: make readme", file=sys.stderr)
            return 1
        print("ok: README results match the data")
        return 0
    with open(path, "w", encoding="utf-8") as f:
        f.write(wanted)
    print("README.md results updated")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
