#!/usr/bin/env python3

"""Writes the results tables into README.md, built only from the benchmark (v1, v2) and eval data.

The tables sit between two marker lines in README.md. `make readme` rewrites them;
test_readme.py fails when they are out of date (part of `make usage-test`, `make check`
and CI), so no result in the README is typed by hand.
"""

import argparse
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
PR_URL = "https://github.com/amith55555/ai-governed-terraform/pull/"
sys.path.insert(0, HERE)
import report  # noqa: E402

START = "<!-- results:start (generated by `make readme` from the benchmark and eval results; do not edit) -->"
END = "<!-- results:end -->"
EVAL_CONFIGS = ("baseline", "harness")
V2_TASKS = ("C1", "C2", "C3")


def benchmark_section(results):
    by_config = {c: [r for r in results if r["config"] == c] for c in report.CONFIGS}
    if not all(by_config.values()):
        raise report.BadData("the benchmark needs runs for both configurations")
    rows = []
    for config, items in by_config.items():
        rows.append([config, len(items), report.share(items, "ok"), report.share(items, "first_pass"),
                     f"{report.mean([i['pushes'] for i in items]):.1f}",
                     f"{report.mean([i['calls'] for i in items]):.0f}",
                     f"{report.mean([sum(i['tokens'].values()) for i in items]):,.0f}",
                     f"${report.mean([i['cost'] for i in items]):.2f}"])
    base, harness = (report.mean([i["cost"] for i in by_config[c]]) for c in report.CONFIGS)
    task_rows = []
    for task in report.TASKS:
        cells = {c: [r for r in by_config[c] if r["task"] == task] for c in report.CONFIGS}
        if not all(cells.values()):
            continue
        task_rows.append([task] + [report.share(cells[c], "ok") for c in report.CONFIGS]
                         + [f"${report.mean([i['cost'] for i in cells[c]]):.2f}" for c in report.CONFIGS])
    return [
        f"**Benchmark v1** ({len(results)} runs: {len(report.TASKS)} easy tasks, 2 configurations, same model)",
        "",
        report.table(["Config", "Runs", "Success", "First-pass CI", "CI pushes to green", "API calls", "Tokens",
                      "Cost per run"], rows),
        "",
        f"Averages per run. Harness cost per run vs baseline: {(harness - base) / base * 100:+.0f}%.",
        "",
        report.table(["Task", "Success, baseline", "Success, harness", "Cost, baseline", "Cost, harness"], task_rows),
    ]


def session_tokens(session_ids, usage, prices, run_id):
    """Tokens by type and the price-weighted cost of a run's sessions, priced like v1."""
    totals, cost = dict.fromkeys(report.TOKEN_PRICES, 0), 0.0
    for session in session_ids:
        if session not in usage:
            raise report.BadData(f"v2 run {run_id}: session {session} is not in usage.csv (run make usage first)")
        models = usage[session]["models"].split()
        if len(models) != 1 or models[0] not in prices:
            raise report.BadData(f"v2 run {run_id}: no single priced model for session {session}")
        for field, price_key in report.TOKEN_PRICES.items():
            count = report.number(usage[session].get(field, 0))
            totals[field] += count
            cost += count * float(prices[models[0]][price_key]) / 1_000_000
    return totals, cost


def v2_section(runs, review, usage, prices):
    if not runs:
        raise report.BadData("benchmarks/v2/results/v2.csv has no runs")
    rows = []
    for run in runs:
        if run["config"] not in EVAL_CONFIGS or run["task"] not in V2_TASKS:
            raise report.BadData(f"v2 run {run['run_id']}: unknown config or task")
        for field in ("success", "first_pass_ci"):
            if run[field] not in ("yes", "no"):
                raise report.BadData(f"v2 run {run['run_id']}: {field} must be yes or no, not {run[field]!r}")
        tokens, cost = session_tokens(run["session_ids"].split(), usage, prices, run["run_id"])
        reviewed = review.get(run["run_id"], {}).get("reviewed_success", run["success"])
        rows.append({"config": run["config"], "task": run["task"], "ok": run["success"] == "yes",
                     "reviewed": reviewed == "yes", "first_pass": run["first_pass_ci"] == "yes",
                     "minutes": report.number(run["minutes"]), "tools": report.number(run["tool_calls"]),
                     "blocks": report.number(run["guard_blocks"]), "tokens": sum(tokens.values()), "cost": cost})
    by_config = {c: [r for r in rows if r["config"] == c] for c in EVAL_CONFIGS}
    if not all(by_config.values()):
        raise report.BadData("v2 needs runs for both configurations")

    def per_success(items, key):
        wins = sum(1 for i in items if i[key])
        return sum(i["cost"] for i in items) / wins if wins else float("inf")

    table_rows = []
    for config, items in by_config.items():
        cps = per_success(items, "reviewed")
        table_rows.append([config, len(items), report.share(items, "reviewed"),
                           report.share(items, "first_pass"), f"{report.mean([i['minutes'] for i in items]):.1f}",
                           f"{report.mean([i['tools'] for i in items]):.0f}",
                           f"{report.mean([i['blocks'] for i in items]):.1f}",
                           f"{report.mean([i['tokens'] for i in items]):,.0f}",
                           f"${report.mean([i['cost'] for i in items]):.2f}",
                           "n/a" if cps == float("inf") else f"${cps:.2f}"])
    task_rows = []
    for task in V2_TASKS:
        cells = {c: [r for r in by_config[c] if r["task"] == task] for c in EVAL_CONFIGS}
        if all(cells.values()):
            task_rows.append([task] + [report.share(cells[c], "reviewed") for c in EVAL_CONFIGS]
                             + [f"${report.mean([i['cost'] for i in cells[c]]):.2f}" for c in EVAL_CONFIGS])
    base, harness = by_config["baseline"], by_config["harness"]

    def rule(key):
        wins = {c: sum(1 for i in by_config[c] if i[key]) for c in EVAL_CONFIGS}
        return wins["harness"] - wins["baseline"] >= 2 or (
            wins["harness"] == wins["baseline"] and per_success(harness, key) < per_success(base, key))

    helped, helped_reviewed = rule("ok"), rule("reviewed")
    verdict = "helped" if helped else "did not help"
    if helped == helped_reviewed:
        rule_text = f"the harness **{verdict}** (same result with the corrected verdicts)."
    else:
        rule_text = (f"the harness **{verdict}** by the registered automatic verdicts; with the corrected "
                     f"verdicts it {'helped' if helped_reviewed else 'did not help'}.")
    return [
        f"**Benchmark v2** ({len(runs)} runs: {len(V2_TASKS)} harder tasks, 2 configurations, no sub-agents; "
        "details in [benchmarks/v2/](benchmarks/v2/))",
        "",
        report.table(["Config", "Runs", "Success", "First-pass CI", "Minutes",
                      "Tool calls", "Guard blocks", "Tokens", "Cost per run", "Cost per success"], table_rows),
        "",
        "Averages per run. Success is after reading each PR: the automatic check wrongly failed one harness "
        "run, C1-h2 ([manual-review.csv](benchmarks/v2/results/manual-review.csv)).",
        "",
        report.table(["Task", "Success, baseline", "Success, harness", "Cost, baseline", "Cost, harness"], task_rows),
        "",
        "Pre-registered rule (2 more successes, or equal success at a lower cost per success): " + rule_text,
    ]


def eval_section(rows):
    if not rows:
        raise report.BadData("evals/results.csv has no runs")
    seen, total, lines = {}, {}, []
    for row in rows:
        key = (row["eval_id"], row["config"])
        total[key] = total.get(key, 0) + 1
    passed = 0
    for row in rows:
        if row["config"] not in EVAL_CONFIGS:
            raise report.BadData(f"eval {row['eval_id']}: unknown config {row['config']!r}")
        for field in ("agent_introduced_violation", "passed"):
            if row[field] not in ("yes", "no"):
                raise report.BadData(f"eval {row['eval_id']}: {field} must be yes or no, not {row[field]!r}")
        key = (row["eval_id"], row["config"])
        seen[key] = seen.get(key, 0) + 1
        name = row["eval_id"] + (f" run {seen[key]}" if total[key] > 1 else "")
        pr = f"[#{row['pr']}]({PR_URL}{row['pr']})" if row["pr"].isdigit() else "none"
        passed += row["passed"] == "yes"
        lines.append([name, row["config"], pr, row["agent_introduced_violation"], row["first_layer"],
                      row["mergeable_without_approval"], row["passed"]])
    summary = f"{passed} of {len(rows)} runs passed"
    if passed == len(rows):
        summary += ": no violation became mergeable without the owner's approval"
    return [
        f"**Safety evals** ({len(rows)} runs of 4 planted violations; details in [evals/](evals/))",
        "",
        report.table(["Eval", "Config", "PR", "Violation in the PR", "Stopped by", "Merge state", "Passed"], lines),
        "",
        summary + ".",
    ]


def block(repo=REPO):
    bench = os.path.join(repo, "benchmarks")
    price_rows = report.read_csv(os.path.join(bench, "prices.csv"))
    prices = {p["model"]: p for p in price_rows}
    results = report.runs_with_usage(report.read_csv(os.path.join(bench, "results", "runs.csv")),
                                     report.read_csv(os.path.join(bench, "results", "usage.csv")), prices)
    usage = {row["session_id"]: row for row in report.read_csv(os.path.join(bench, "results", "usage.csv"))}
    v2_dir = os.path.join(bench, "v2", "results")
    v2_runs = report.read_csv(os.path.join(v2_dir, "v2.csv"))
    review_path = os.path.join(v2_dir, "manual-review.csv")
    review = {r["run_id"]: r for r in report.read_csv(review_path)} if os.path.exists(review_path) else {}
    evals = report.read_csv(os.path.join(repo, "evals", "results.csv"))
    return "\n".join([START, ""] + benchmark_section(results) + [""] + v2_section(v2_runs, review, usage, prices)
                     + [""] + eval_section(evals) + ["", END])


def replace_block(text, new_block):
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        raise report.BadData("README.md needs exactly one results:start line before one results:end line")
    before, rest = text.split(START, 1)
    after = rest.split(END, 1)[1]
    return before + new_block + after


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if README.md is out of date; change nothing")
    parser.add_argument("--repo", default=REPO)
    args = parser.parse_args(argv)
    path = os.path.join(args.repo, "README.md")
    try:
        with open(path, encoding="utf-8") as f:
            current = f.read()
        wanted = replace_block(current, block(args.repo))
    except (report.BadData, OSError, KeyError, ValueError, csv.Error) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if wanted != current:
            print("FAIL: the README results are out of date. Run: make readme", file=sys.stderr)
            return 1
        print("ok: README results match the data")
        return 0
    with open(path, "w", encoding="utf-8") as f:
        f.write(wanted)
    print("README.md results updated")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
